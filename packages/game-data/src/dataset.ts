// @effect-migrated
import { Effect, FileSystem, Path, Predicate, Schema } from 'effect';
import type { AtlasLootError } from './atlasloot.ts';
import { isList, luaModule, type LuaValue } from './lua.ts';
import type { TableReadError } from './wago.ts';

// Where a dataset's file goes and in which form:
//   lua  → addon/WispAI/Data/<Name>.lua as ns.Data.<Name>; loaded in game, so keep it small.
//   json → a JSON file the bridge reads; for data the agent uses directly or
//          that is too large to hold in the game's memory.
export type Output =
  | { format: 'lua'; path: string; name: string }
  | { format: 'json'; path: string };

/** A dataset's inputs (the pin, curated facts, game tables) do not give it what it needs. */
export class DatasetError extends Schema.TaggedError<DatasetError>()('DatasetError', {
  message: Schema.String,
}) {}

export type DatasetFailure = DatasetError | TableReadError | AtlasLootError;

// One generated file. build reads the game tables it needs (and any other
// source in R) and returns plain data; render() writes it with a header
// naming the build and tables.
export interface Dataset<R = never> {
  name: string;
  description: string;
  tables: string[];
  output: Output;
  // Sources besides the game tables, named in the file header with their licence.
  credits?: string;
  build: Effect.Effect<LuaValue, DatasetFailure, R>;
}

// A fact the game tables do not carry, kept with where it came from.
export const Curated = <S extends Schema.Top>(value: S) =>
  Schema.Struct({ value, source: Schema.String, note: Schema.optionalKey(Schema.String) });

const failure = (cause: unknown) =>
  new DatasetError({ message: Predicate.isError(cause) ? cause.message : String(cause) });

// Runs a dataset's plain transform, whose row reads (num, str) throw on a
// missing or malformed column.
export const fromRows = <A>(transform: () => A) => Effect.try({ try: transform, catch: failure });

// Reads and decodes a JSON file of this package, such as build.json or
// curated/<name>.json.
export const readPackageJson = Effect.fnUntraced(function* <S extends Schema.Decoder<unknown>>(
  file: string,
  schema: S,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const text = yield* path
    .fromFileUrl(new URL(`../${file}`, import.meta.url))
    .pipe(Effect.flatMap(fs.readFileString), Effect.mapError(failure));
  return yield* Schema.decodeEffect(Schema.fromJsonString(schema))(text).pipe(
    Effect.mapError(failure),
  );
});

function sorted(value: LuaValue): LuaValue {
  if (isList(value)) {
    return value.map(sorted);
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .filter((key) => value[key] !== undefined)
        .map((key) => [key, sorted(value[key])]),
    );
  }
  return value;
}

export function render<R>(dataset: Dataset<R>, value: LuaValue, build: string): string {
  const header = [
    `Generated by packages/game-data (dataset "${dataset.name}") from World of Warcraft: Forever`,
    `build ${build} game tables (${dataset.tables.join(', ')}) via wago.tools. Do not edit: run`,
    `pnpm data:generate after a patch. ${dataset.description}`,
    ...(dataset.credits ? [dataset.credits] : []),
  ];
  if (dataset.output.format === 'lua') {
    return luaModule(dataset.output.name, header, value);
  }
  return (
    JSON.stringify(
      {
        generated: { dataset: dataset.name, build, tables: dataset.tables, note: header.join(' ') },
        data: sorted(value),
      },
      null,
      2,
    ) + '\n'
  );
}
