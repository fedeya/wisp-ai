import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

// Sources are pinned by content as well as Unicode version. Runtime Lua has no
// dependency on JavaScript, host locale, UTF-8 modules, or network access.
const sources = [
  {
    name: 'UnicodeData.txt',
    sha: 'ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f',
    url: 'https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/16.0.0/UnicodeData.txt',
  },
  {
    name: 'CaseFolding.txt',
    sha: '6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb',
    url: 'https://raw.githubusercontent.com/unicode-org/unicodetools/main/unicodetools/data/ucd/16.0.0/CaseFolding.txt',
  },
  {
    name: 'entities.json',
    sha: 'd741d877ac77c4194c4ad526b5b4a19aef8dfe411ab840a466891cdbb9f362e6',
    url: 'https://html.spec.whatwg.org/entities.json',
  },
];

function luaString(value: string): string {
  const escaped = Array.from(value, (character) => {
    if (character === '"' || character === '\\') {
      return '\\' + character;
    }
    const code = character.codePointAt(0)!;
    return code < 32 || code === 127 ? '\\' + code.toString().padStart(3, '0') : character;
  }).join('');
  return '"' + escaped + '"';
}

const inputDir = process.argv[2];
const inputs: Record<string, string> = {};
for (const source of sources) {
  const bytes = inputDir
    ? await readFile(resolve(inputDir, source.name))
    : Buffer.from(await (await fetch(source.url)).arrayBuffer());
  if (createHash('sha256').update(bytes).digest('hex') !== source.sha) {
    throw new Error('Source checksum changed: ' + source.name);
  }
  inputs[source.name] = bytes.toString('utf8');
}

const punctuation: number[] = [];
const unicodePunctuation: number[] = [];
for (const line of inputs['UnicodeData.txt'].split('\n')) {
  const fields = line.split(';');
  if (/^[PS]/.test(fields[2] ?? '')) {
    punctuation.push(parseInt(fields[0], 16));
  }
  if ((fields[2] ?? '').startsWith('P')) {
    unicodePunctuation.push(parseInt(fields[0], 16));
  }
}
const ranges: number[] = [];
for (const code of punctuation) {
  if (ranges.length && ranges.at(-1)! + 1 === code) {
    ranges[ranges.length - 1] = code;
  } else {
    ranges.push(code, code);
  }
}
const unicodeRanges: number[] = [];
for (const code of unicodePunctuation) {
  if (unicodeRanges.length && unicodeRanges.at(-1)! + 1 === code) {
    unicodeRanges[unicodeRanges.length - 1] = code;
  } else {
    unicodeRanges.push(code, code);
  }
}

const folds = new Map<number, string>();
for (const line of inputs['CaseFolding.txt'].split('\n')) {
  const [code, status, mapping] = line.split(';').map((part) => part.trim());
  if (status === 'C' || status === 'F') {
    folds.set(
      parseInt(code, 16),
      String.fromCodePoint(...mapping.split(' ').map((n) => parseInt(n, 16))),
    );
  }
}
const entities = JSON.parse(inputs['entities.json']) as Record<string, { characters: string }>;
const lines = [
  '-- Generated by scripts/generate-markdown-data.ts; do not edit by hand.',
  '-- Unicode 16.0.0 (Unicode License v3); WHATWG HTML named character references.',
  '-- Source URLs and checksums live in the generator; licenses in this directory.',
  'local _, C = ...',
  '-- stylua: ignore',
  'C.Markdown.Data = {',
  '    unicodeVersion = "16.0.0",',
  '    punctuation = {',
];
for (let i = 0; i < ranges.length; i += 16) {
  lines.push('        ' + ranges.slice(i, i + 16).join(', ') + ',');
}
lines.push('    },', '    unicodePunctuation = {');
for (let i = 0; i < unicodeRanges.length; i += 16) {
  lines.push('        ' + unicodeRanges.slice(i, i + 16).join(', ') + ',');
}
lines.push('    },', '    casefold = {');
for (const [code, mapping] of folds) {
  lines.push(`        [${code}] = ${luaString(mapping)},`);
}
lines.push('    },', '    entities = {');
for (const name of Object.keys(entities)
  .filter((name) => name.endsWith(';'))
  .sort()) {
  lines.push(
    `        [${luaString(name.slice(1, -1))}] = ${luaString(entities[name].characters)},`,
  );
}
lines.push('    },', '}', '');
const target = fileURLToPath(new URL('../addon/WispAI/Markdown/Data.lua', import.meta.url));
await writeFile(target, lines.join('\n'));
console.log(
  `${basename(target)}: ${ranges.length / 2} Unicode ranges, ${folds.size} case folds, ${Object.keys(entities).filter((name) => name.endsWith(';')).length} entities`,
);
