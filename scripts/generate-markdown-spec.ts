import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

type Example = {
  example: number;
  section: string;
  markdown: string;
  html: string;
  checkOnly?: boolean;
};
const root = fileURLToPath(new URL('../addon/tests/fixtures/markdown/', import.meta.url));
await mkdir(root, { recursive: true });
const sources = [
  {
    name: 'commonmark-spec.json',
    sha: 'd431b29d97b6f73e69d547109cf5081578fac931e72afe95639ebe766c1b2a20',
    url: 'https://spec.commonmark.org/0.31.2/spec.json',
    target: 'commonmark.lua',
    version: 'CommonMark 0.31.2',
  },
  {
    name: 'gfm-extensions.txt',
    sha: 'a2a45e98be9fca95f564f927265a0f63beea6cae5369d1cf4bde44caa51b2a3a',
    url: 'https://raw.githubusercontent.com/github/cmark-gfm/27d942c8b0a62d192f616e5bf3578f4b6a89e180/test/extensions.txt',
    target: 'gfm-additional.lua',
    version: 'cmark-gfm extension regression examples (GFM features only)',
  },
  {
    name: 'gfm.html',
    sha: 'b153d814fdfc8624bb6da7449162c1cd707a637f7d1c1b636eb44b9cf63fa220',
    url: 'https://github.github.com/gfm/',
    target: 'gfm.lua',
    version: 'GFM 0.29-gfm official extension examples',
  },
];

function quote(value: string): string {
  const escaped = Array.from(value, (character) => {
    if (character === '"' || character === '\\') {
      return '\\' + character;
    }
    const code = character.codePointAt(0)!;
    return code < 32 || code === 127 ? '\\' + code.toString().padStart(3, '0') : character;
  }).join('');
  return '"' + escaped + '"';
}

for (const source of sources) {
  const bytes = process.argv[2]
    ? await readFile(resolve(process.argv[2], source.name))
    : Buffer.from(await (await fetch(source.url)).arrayBuffer());
  if (createHash('sha256').update(bytes).digest('hex') !== source.sha) {
    throw new Error('Source checksum changed: ' + source.name);
  }
  let examples: Example[];
  if (source.name.endsWith('.json')) {
    examples = JSON.parse(bytes.toString('utf8')) as Example[];
  } else if (source.name.endsWith('.html')) {
    examples = [];
    const extensions = new Set([
      'tables-extension-',
      'task-list-items-extension-',
      'strikethrough-extension-',
      'autolinks-extension-',
      'disallowed-raw-html-extension-',
    ]);
    let section = '',
      level = 0;
    const html = bytes.toString('utf8');
    const records =
      /<h([1-6])[^>]*id="([^"]+)"[^>]*>[\s\S]*?<\/h[1-6]>|<div class="example" id="example-(\d+)">[\s\S]*?<pre><code class="language-markdown">([\s\S]*?)<\/code><\/pre>[\s\S]*?<pre><code class="language-html">([\s\S]*?)<\/code><\/pre>/g;
    function decode(fragment: string) {
      return fragment
        .replace(/<[^>]*>/g, '')
        .replace(
          /&(?:amp|lt|gt|quot|#39);/g,
          (entity) =>
            ({ '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" })[entity]!,
        )
        .replace(/→/g, '\t');
    }
    for (const match of html.matchAll(records)) {
      if (match[1]) {
        if (extensions.has(match[2])) {
          section = match[2];
          level = Number(match[1]);
        } else if (Number(match[1]) <= level) {
          section = '';
        }
      } else if (section) {
        examples.push({
          example: Number(match[3]),
          section,
          markdown: decode(match[4]),
          html: decode(match[5]),
        });
      }
    }
    if (!examples.length) {
      throw new Error('No official GFM examples extracted');
    }
  } else {
    examples = [];
    const features = new Set([
      'Tables',
      'Strikethroughs',
      'Autolinks',
      'HTML tag filter',
      'Interop',
      'Task lists',
    ]);
    let section = '',
      feature = '',
      id = 0,
      block: 'markdown' | 'html' | undefined,
      markdown = '',
      html = '';
    for (const line of bytes.toString('utf8').replace(/\r\n/g, '\n').split('\n')) {
      if (!block && /^#+ /.test(line)) {
        section = line.replace(/^#+ /, '');
      }
      if (!block && line.startsWith('## ')) {
        feature = section;
      }
      if (!block && /^`+ example/.test(line)) {
        block = 'markdown';
        markdown = '';
        html = '';
      } else if (block === 'markdown' && line === '.') {
        block = 'html';
      } else if (block === 'html' && /^`{10,}$/.test(line)) {
        id++;
        if (features.has(feature)) {
          examples.push({ example: id, section, markdown, html, checkOnly: html === '<IGNORE>\n' });
        }
        block = undefined;
      } else if (block) {
        if (block === 'markdown') {
          markdown += line.replace(/→/g, '\t') + '\n';
        } else {
          html += line.replace(/→/g, '\t') + '\n';
        }
      }
    }
  }
  const lines = [
    '-- Generated by scripts/generate-markdown-spec.ts.',
    '-- ' + source.version + ': ' + source.url,
    '-- Examples licensed CC BY-SA 4.0; attribution and change notice in README.md.',
    '-- stylua: ignore',
    'return {',
  ];
  for (const example of examples) {
    lines.push(
      `    { id = ${example.example}, section = ${quote(example.section)}, markdown = ${quote(example.markdown)}, html = ${quote(example.html)}${example.checkOnly ? ', checkOnly = true' : ''} },`,
    );
  }
  lines.push('}', '');
  await writeFile(resolve(root, source.target), lines.join('\n'));
  console.log(`${source.target}: ${examples.length} official examples`);
}
