param([Parameter(Mandatory=$true)][string]$Source)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$root = Split-Path $PSScriptRoot -Parent
$out = Join-Path $root 'addon/WispAI/Textures/Emoji'
New-Item -ItemType Directory -Force -Path $out | Out-Null
$files = @(Get-ChildItem -LiteralPath (Join-Path $Source 'assets/72x72') -Filter '*.png' | Sort-Object Name)
$data = [System.Collections.Generic.List[string]]::new()
$data.Add('-- Generated by scripts/build-emoji.ps1 from Twemoji v17.0.3 (CC BY 4.0).')
$data.Add('local _, ns = ...')
$data.Add('ns.UI.EmojiData = {')
for ($page = 0; $page * 1024 -lt $files.Count; $page++) {
    $bitmap = [System.Drawing.Bitmap]::new(1024, 1024, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    $graphics.Clear([System.Drawing.Color]::Transparent)
    $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $graphics.CompositingMode = [System.Drawing.Drawing2D.CompositingMode]::SourceCopy
    for ($cell = 0; $cell -lt 1024; $cell++) {
        $index = $page * 1024 + $cell
        if ($index -ge $files.Count) { break }
        $file = $files[$index]
        $image = [System.Drawing.Image]::FromFile($file.FullName)
        $graphics.DrawImage($image, [int](($cell % 32) * 32 + 1), [int]([Math]::Floor($cell / 32) * 32 + 1), 30, 30)
        $image.Dispose()
        $emoji = -join ($file.BaseName.Split('-') | Where-Object { $_ -ne 'fe0f' } | ForEach-Object { [char]::ConvertFromUtf32([Convert]::ToInt32($_,16)) })
        $data.Add('    ["' + $emoji + '"] = ' + $index + ',')
    }
    $graphics.Dispose()
    $bits = $bitmap.LockBits([System.Drawing.Rectangle]::new(0,0,1024,1024), [System.Drawing.Imaging.ImageLockMode]::ReadOnly, [System.Drawing.Imaging.PixelFormat]::Format32bppArgb)
    $pixels = [byte[]]::new(1024 * 1024 * 4)
    [System.Runtime.InteropServices.Marshal]::Copy($bits.Scan0, $pixels, 0, $pixels.Length)
    $bitmap.UnlockBits($bits)
    $stream = [System.IO.File]::Create((Join-Path $out "Emoji$page.tga"))
    # Uncompressed BGRA, bottom-left origin, eight alpha bits.
    $header = [byte[]]::new(18)
    $header[2]=2; $header[13]=4; $header[15]=4; $header[16]=32; $header[17]=8
    $stream.Write($header,0,18)
    for ($row=1023; $row -ge 0; $row--) { $stream.Write($pixels,$row*4096,4096) }
    $stream.Dispose()
    $bitmap.Dispose()
}
$data.Add('}')
[System.IO.File]::WriteAllText((Join-Path $root 'addon/WispAI/UI/EmojiData.lua'), ($data -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
$licenseText = [System.IO.File]::ReadAllText((Join-Path $Source 'LICENSE-GRAPHICS'))
$licenseText = [regex]::Replace($licenseText, '(?m)[ \t]+$', '')
[System.IO.File]::WriteAllText((Join-Path $out 'LICENSE-GRAPHICS.txt'), $licenseText, [System.Text.UTF8Encoding]::new($false))
Write-Output "Packed $($files.Count) Twemoji graphics into $($page) atlases."
